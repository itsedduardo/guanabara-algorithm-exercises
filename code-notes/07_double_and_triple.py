# Make a algorithm that reads a float and returns the double and triple of it's value.

user_input = float(input("Write a number: "))

print(f"Number: {user_input}")
print(f"The double of {user_input} is: {user_input * 2}")
print(f"The triple of {user_input} is: {user_input * 3}")








